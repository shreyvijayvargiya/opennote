export const encodeIcon = {
	icon: (name) => `hugeicons:${name}`,
	emoji: (e) => `emoji:${e}`,
};

/** "hugeicons:Rocket01Icon" -> { type: "icon", value: ICONS.Rocket01Icon } */
export const parseIcon = (value) => {
	if (!value) return null;
	if (value.startsWith("emoji:")) return { type: "emoji", value: value.slice(6) };
	if (value.startsWith("hugeicons:") && ICONS[value.slice(10)]) {
		return { type: "icon", value: ICONS[value.slice(10)] };
	}
	return null;
};
